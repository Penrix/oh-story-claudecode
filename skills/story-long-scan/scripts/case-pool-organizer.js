function matches(rule, title, intro) {
  return (rule.title && rule.title.test(title)) || (rule.intro && rule.intro.test(intro));
}

function classifyCaseWater(item) {
  const title = String(item && item.title ? item.title : "");
  const intro = String(item && item.intro ? item.intro : "");

  for (const rule of RULES) {
    if (matches(rule, title, intro)) {
      return { section: rule.section, group: rule.group };
    }
  }

  const firstFrame = `${title} ${intro.slice(0, 320)}`;
  for (const rule of FALLBACK_RULES) {
    if (rule.pattern.test(firstFrame)) {
      return { section: rule.section, group: rule.group };
    }
  }

  return { section: "待归位", group: "待归位" };
}

function organizeCases(cases) {
  const buckets = new Map();

  for (const entry of WATER_ORDER) {
    for (const group of entry.groups) {
      buckets.set(`${entry.section}\u0000${group}`, []);
    }
  }

  for (const item of cases || []) {
    const where = classifyCaseWater(item);
    const key = `${where.section}\u0000${where.group}`;
    if (!buckets.has(key)) buckets.set(key, []);
    buckets.get(key).push(item);
  }

  return WATER_ORDER.map((entry) => ({
    section: entry.section,
    groups: entry.groups
      .map((group) => ({
        group,
        cases: buckets.get(`${entry.section}\u0000${group}`) || [],
      }))
      .filter((x) => x.cases.length > 0),
  })).filter((entry) => entry.groups.length > 0);
}

function renderCaseMarkdown(cases) {
  const lines = [
    "# 榜单数据",
    "",
    "> 分类只用于第三代生产中的“目标母体 / IP / 题材”检索坐标；每个 Case 的生成颗粒仍然只有书名 + 完整简介。",
    "> 不按平台、榜种、排名拆库，不从简介提炼卖点/爽点；证据不足的 Case 保留在“待归位”。",
    "",
  ];

  for (const section of organizeCases(cases)) {
    lines.push(`## ${section.section}`, "");

    for (const group of section.groups) {
      lines.push(`### ${group.group}`, "");

      for (const item of group.cases) {
        lines.push(`#### 《${item.title}》`, "", item.intro, "", "---", "");
      }
    }
  }

  return lines.join("\n");
}

